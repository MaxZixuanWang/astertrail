test('Chinese star names and aliases find the same target', () => {
  assert.equal(index.search('天狼')[0].id, 'HIP32349');
  assert.equal(index.search('织女一')[0].id, 'HIP91262');
  assert.equal(index.search('七姐妹')[0].id, 'M45');
  assert.equal(index.search('仙女座')[0].id, 'M31');
  assert.equal(index.search('sIrIuS')[0].kind, 'star');
});

test('Messier numbers normalize case, whitespace, leading zeros and full-width input', () => {
  for (const query of ['M31', 'm 31', 'M031', '梅西耶31', '梅西耶 031', 'Messier 31', 'Ｍ０３１']) {
    assert.equal(index.search(query)[0].id, 'M31', query);
    assert.equal(index.get(query).id, 'M31', query);
  }
});

test('exact target IDs rank before prefix suggestions while typing', () => {
  assert.deepEqual(index.search('M3').map(item => item.id), ['M3', 'M31', 'M32']);
  assert.equal(index.search('HIP 032349')[0].id, 'HIP32349');
  assert.equal(index.get('hip 032349').id, 'HIP32349');
  assert.equal(index.search('仙女', 1).length, 1);
});

test('empty query browses the alphabetic catalog, unknown query stays empty and source is unchanged', () => {
  assert.deepEqual(index.search('').slice(0, 3).map(item => item.id), ['M42', 'M3', 'M45']);
  assert.equal(index.browse('').total, fixture.stars.length + fixture.messier.length);
  assert.deepEqual(index.search(''), index.search('   '));
  assert.deepEqual(index.search('不存在的星星'), []);
  assert.deepEqual(index.search('M', 0), []);
  assert.equal(index.get('M999'), null);
  assert.equal(fixture.stars[0].kind, undefined);
});

