test('orientation reconstructs the rotated phone axes including zenith and landscape', () => {
  // Independent sequential rotations, instead of repeating the combined matrix.
  function rotate(vector, alpha, beta, gamma) {
    let [x, y, z] = vector;
    const a = alpha * RAD, b = beta * RAD, g = gamma * RAD;
    [x, z] = [x * Math.cos(g) + z * Math.sin(g), -x * Math.sin(g) + z * Math.cos(g)];
    [y, z] = [y * Math.cos(b) - z * Math.sin(b), y * Math.sin(b) + z * Math.cos(b)];
    [x, y] = [x * Math.cos(a) - y * Math.sin(a), x * Math.sin(a) + y * Math.cos(a)];
    return [x, y, z];
  }
  for (const alpha of [0, 87, 270]) for (const beta of [-179, -90, 0, 90, 179, 180]) {
    for (const gamma of [-89, 0, 40]) for (const screen of [0, 90, 180, 270]) {
      const result = astro.cameraBasis(astro.orientationToCamera(alpha, beta, gamma, screen));
      vectorClose(result.forward, rotate([0, 0, -1], alpha, beta, gamma));
      vectorClose(result.up, rotate([Math.sin(screen * RAD), Math.cos(screen * RAD), 0], alpha, beta, gamma));
    }
  }
});

test('sensor radians must be converted explicitly before W3C core usage', () => {
  const radians = { alpha: Math.PI / 2, beta: Math.PI / 2, gamma: 0 };
  const camera = astro.orientationToCamera(radians.alpha / RAD, radians.beta / RAD, radians.gamma / RAD);
  close(camera.az, 270);
  close(camera.alt, 0);
});

